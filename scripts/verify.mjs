/** 把折行拼回一行，便于正则匹配（控制台宽度不同会改变换行位置）。 */
function 归一化(文本) {
  return 文本.replace(/\r?\n/g, ' ')
}

/** 取出 `标签` 之后、下一个日志标记之前的所有 `名=数字` 对。 */
function 取计数(全文, 标签) {
  const 起点 = 全文.indexOf(标签)
  if (起点 < 0) return null
  const 之后 = 全文.slice(起点 + 标签.length)
  const 切断 = 之后.search(/\[selfMD\]|\[renderer:|\[smoke\]/)
  const 片段 = 切断 >= 0 ? 之后.slice(0, 切断) : 之后
  const 结果 = {}
  for (const 匹配 of 片段.matchAll(/([\p{L}\p{N}_]+)=(\d+)/gu)) {
    结果[匹配[1]] = Number(匹配[2])
  }
  return 结果
}

/** 取出编辑命令自测的用例名 → 输出。 */
function 取命令结果(全文) {
  const 结果 = {}
  // 日志格式固定为 `    ${用例名}  →  ${输出}`（箭头两侧各两个空格）。
  // 这里**必须**精确匹配这两个空格，不能用 `\s+`：缩进用例的输出本身就以
  // 空格开头（`    甲`），用 `\s+` 会把有意义的前导空白一并吃掉，
  // 让一条本来正确的行为看起来像失败。
  for (const 匹配 of 全文.matchAll(/^\s{4}(.+?)\s{2}→\s{2}(.*)$/gmu)) {
    结果[匹配[1]] = 匹配[2]
  }
  return 结果
}

/** 取出纯函数自测的用例名 → 输出（分隔符是 `=>`，与命令自测区分开）。 */
function 取纯函数结果(全文) {
  const 结果 = {}
  for (const 匹配 of 全文.matchAll(/^\s{4}(.+?)\s{2}=>\s{2}(.*)$/gmu)) {
    结果[匹配[1]] = 匹配[2]
  }
  return 结果
}

/**
 * 命令注册表的静态检查。
 *
 * Electron 遇到重复的菜单加速键时会**静默**采用第一个，第二个永远按不出来，
 * 界面上没有任何迹象。所以只能在注册表层面查——这是本项目第三处
 * "失败是沉默的、必须主动断言"的地方（另两处是装饰层与撤销粒度）。
 */
function 检查注册表() {
  const 源 = readFileSync(join(项目根, 'src', 'shared', 'commands.ts'), 'utf8')
  const 加速键 = new Map()
  for (const 匹配 of 源.matchAll(
    /id: '([^']+)',[^}]*?accelerator: '([^']+)'/g
  )) {
    const [, id, 键] = 匹配
    if (!加速键.has(键)) 加速键.set(键, [])
    加速键.get(键).push(id)
  }
  const 冲突 = [...加速键.entries()].filter(([, ids]) => ids.length > 1)
  return { 总数: 加速键.size, 冲突 }
}

// ---------------------------------------------------------------------------
// 运行一次冒烟测试
// ---------------------------------------------------------------------------

function 运行冒烟(样本路径, 额外参数 = []) {
  const 输出文件 = join(临时目录, 'out.log')
  const fd = openSync(输出文件, 'w')
  const 参数 = [join(项目根, 'scripts', 'smoke.mjs')]
  if (样本路径) 参数.push(`--smoke-open=${样本路径}`)
  参数.push(...额外参数)
  const 子进程 = spawn(process.execPath, 参数, {
    cwd: 项目根,
    stdio: ['ignore', fd, fd]
  })
  return new Promise((完成) => {
    子进程.on('exit', (码) => {
      closeSync(fd)
      const 文本 = readFileSync(输出文件, 'utf8')
      try {
        rmSync(输出文件, { force: true })
      } catch {
        /* 清理失败不影响判定 */
      }
      完成({ 码, 文本 })
    })
  })
}

