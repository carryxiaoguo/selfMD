/** 扁平化后的全部设置项，供校验与遍历使用。 */
export function 全部设置项(): 设置项[] {
  return 偏好设置结构.flatMap((分区) => 分区.小节.flatMap((小节) => 小节.项))
}

/**
 * 校验表里的每个键都真实存在于设置中。
 *
 * 返回不存在的键名数组；界面渲染前调用，出错时能立刻定位到是哪一项写错了，
 * 而不是让用户点一个永远没反应的开关。
 */
export function 校验设置表(): string[] {
  const 已知 = new Set(Object.keys(DEFAULT_SETTINGS))
  return 全部设置项()
    .map((项) => 项.键 as string)
    .filter((键) => !已知.has(键))
}
