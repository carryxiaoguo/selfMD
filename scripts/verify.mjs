let 通过数 = 0
const 失败列表 = []

function 断言(条件, 描述) {
  if (条件) {
    通过数 += 1
  } else {
    失败列表.push(描述)
  }
}

function 比对计数(实际, 期望, 类别, 样本名, 前缀) {
  for (const [名, 期望值] of Object.entries(期望)) {
    const 实际值 = 实际?.[名]
    断言(
      实际值 === 期望值,
      `${样本名} · ${类别} ${名}：期望 ${期望值}，实际 ${实际值 ?? '缺失'}`
    )
  }
}

async function 主流程() {
  console.log('=== selfMD 回归验证 ===')
  console.log('')

  for (const 样本 of 样本断言) {
    const { 码, 文本 } = await 运行冒烟(样本.文件)
    const 全文 = 归一化(文本)

    // 冒烟进程本身必须成功，否则后面的对账没有意义。
    断言(码 === 0, `${样本.文件} · 冒烟进程退出码应为 0，实际 ${码}`)

    // 任何渲染层异常都算失败——装饰层降级是静默的，只能靠日志抓。
    断言(
      !/\[renderer:error\]/.test(文本),
      `${样本.文件} · 渲染层不应输出 error 日志`
    )

    const 解析 = 取计数(全文, '解析树计数：')
    const 渲染 = 取计数(全文, '渲染 DOM 计数：')
    断言(解析 !== null, `${样本.文件} · 应输出解析树计数`)
    断言(渲染 !== null, `${样本.文件} · 应输出渲染 DOM 计数`)

    比对计数(解析, 样本.解析树, '解析树', 样本.说明, '')
    比对计数(渲染, 样本.渲染, '渲染', 样本.说明, '')

    console.log(
      `  ${样本.文件.padEnd(26)} 解析树 ${Object.keys(解析 ?? {}).length} 项 · 渲染 ${Object.keys(渲染 ?? {}).length} 项`
    )
  }

  // 命令自测只需要跑一次（每份样本都会输出，取最后一份即可）。
  const { 文本 } = await 运行冒烟('fixtures/块级最小.md')
  const 命令实际 = 取命令结果(文本)
  for (const [名, 期望] of Object.entries(命令断言)) {
    断言(
      命令实际[名] === 期望,
      `编辑命令「${名}」：期望 ${JSON.stringify(期望)}，实际 ${JSON.stringify(命令实际[名] ?? '缺失')}`
    )
  }
  console.log(`  ${'编辑命令自测'.padEnd(24)} ${Object.keys(命令实际).length} 条`)

  // ------------------------------------------------------------ 纯函数 --
  // 纯函数自测与图片管线自测都用 `=>` 分隔，一次解析即可覆盖两段。
  const 纯函数实际 = 取纯函数结果(文本)
  for (const [名, 期望] of Object.entries({ ...纯函数断言, ...图片断言, ...大纲断言, ...导出断言, ...偏好设置断言, ...上传断言, ...数学断言, ...标点断言, ...匹配断言 })) {
    断言(
      纯函数实际[名] === 期望,
      `纯函数「${名}」：期望 ${JSON.stringify(期望)}，实际 ${JSON.stringify(纯函数实际[名] ?? '缺失')}`
    )
  }
  console.log(`  ${'纯函数与图片管线自测'.padEnd(20)} ${Object.keys(纯函数实际).length} 条`)

  // -------------------------------------------------------- 注册表检查 --
  {
    const { 总数, 冲突 } = 检查注册表()
    断言(
      冲突.length === 0,
      `菜单加速键不得重复，冲突：${冲突.map(([键, ids]) => `${键}（${ids.join('、')}）`).join('；')}`
    )
    console.log(`  ${'菜单加速键'.padEnd(26)} ${总数} 个，无冲突`)
  }

  // ------------------------------------------------------------ 菜单语言 --
  // 原生菜单由操作系统绘制，无头测试截不到图，所以改从日志逐条校验标签语言。
  // 这条断言的价值在于：以后任何人往注册表里加一条英文标签，验证会直接失败。
  {
    const { 文本: 菜单输出 } = await 运行冒烟(null)
    const 标签们 = []
    for (const 行 of 菜单输出.split(/\r?\n/)) {
      // 顶层：`  文件（8/19 可用）`
      const 顶层 = /^ {2}([^（]+)（\d+\/\d+ 可用）/.exec(行)
      if (顶层) {
        标签们.push(顶层[1].trim())
        continue
      }
      // 子项：`      新建  [CmdOrCtrl+N]` / `      导出  ← 未实现`
      // 嵌套子菜单会再缩进 4 格，所以这里用 `{6,}` 而不是精确的 6 格。
      const 子项 = /^ {6,}(.+?)(?: {2}\[| {2}←|$)/.exec(行)
      if (子项) {
        const 标签 = 子项[1].trim()
        // 最近文件列表是动态路径，可能是英文，跳过。
        if (标签 && !标签.includes('\\') && !标签.includes('/') && !标签.startsWith('📌')) {
          标签们.push(标签)
        }
      }
    }

    断言(标签们.length > 50, `菜单标签数量应大于 50，实际 ${标签们.length}`)

    // ---------------------------------------------------------- 实现率 --
    // 菜单摘要里每行顶层分类都带 `(可用/总数)`。把这些数字加起来，
    // 就能知道**还有多少菜单项是灰着的**——这个数只该往下走。
    //
    // 注意这里统计的是**菜单里出现的**命令，不是注册表全量：
    // 注册表还有一些只挂快捷键、不进菜单的命令。所以总数比注册表小。
    //
    // 为什么值得断言：菜单项"能点但没反应"和"灰着不能点"是两回事，
    // 而注册表里的标记与实际有没有处理函数是两处独立的信息，
    // 很容易出现"写了处理函数却忘了改标记"（本轮就抓到四处）。
    let 可用 = 0
    let 总数 = 0
    for (const 行 of 菜单输出.split(/\r?\n/)) {
      const 顶层 = /^ {2}[^（]+（(\d+)\/(\d+) 可用）/.exec(行)
      if (顶层) {
        可用 += Number(顶层[1])
        总数 += Number(顶层[2])
      }
    }

    断言(总数 >= 90, `菜单命令总数应不少于 90，实际 ${总数}`)
    // 已实现的命令数只该增长。写成下界而不是等值：新增命令时不必改这条。
    断言(可用 >= 92, `已实现的菜单命令数不应低于 92，实际 ${可用}`)
    console.log(
      `  ${'菜单命令实现率'.padEnd(30)} ${可用}/${总数}（灰着 ${总数 - 可用} 项）`
    )

    const 含中文 = /[\u4e00-\u9fff]/

    /**
     * 允许保留拉丁字母的标签：**格式名与技术专名**。
     *
     * 这些不是"没翻译"，而是本来就该这么写——把 HTML 译成「超文本标记语言」、
     * 把 PDF 译成「便携文档格式」，用户反而认不出来。格式名本来就该保留原文：
     * 语言包里 `'HTML (without Styles)'` 译作 `'HTML (无样式)'`，
     * 英文原样保留。
     *
     * 白名单是**精确匹配**而不是包含匹配：写漏一个就会红，
     * 从而逼着后来者显式决定"这算专名还是漏译"。
     */
    const 允许的专名 = new Set([
      'HTML',
      'PDF',
      'Word (.docx)',
      'LaTeX',
      'ePub',
      'RTF',
      'OpenDocument (.odt)'
    ])

    const 纯英文 = 标签们.filter((t) => !含中文.test(t) && !允许的专名.has(t.trim()))
    断言(
      纯英文.length === 0,
      `菜单标签应全部包含中文（格式名与技术专名除外），以下为纯英文：${纯英文.join('、')}`
    )

    console.log(
      `  ${'菜单标签'.padEnd(26)} ${标签们.length} 条，全部含中文` +
        `（${允许的专名.size} 个格式专名保留原文）`
    )

    // ---------------------------------------------------------- 图标 --
    // "文件存在"不等于"能用"：路径写错、PNG 损坏、分辨率不对，
    // 都只有实际让 Electron 解码一次才知道。
    const 图标 = /窗口图标：(.+?)\s{2}(\d+)×(\d+)\s{2}(\S+)/.exec(菜单输出)
    断言(图标 !== null, '应输出窗口图标信息')
    if (图标) {
      断言(图标[2] === '256' && 图标[3] === '256', `窗口图标应为 256×256，实际 ${图标[2]}×${图标[3]}`)
      断言(图标[4] === '可正常解码', `窗口图标应能正常解码，实际「${图标[4]}」`)
      console.log(`  ${'应用图标'.padEnd(28)} ${图标[2]}×${图标[3]}，${图标[4]}`)
    }
    断言(!/附属图标 \S+：缺失/.test(菜单输出), '图标集应完整（ico / 16 / 64）')

    // -------------------------------------------------------- 主题协议 --
    // 关键能力是"主题旁边的资源子目录能被加载"——主题的字体、图片、深色子样式表
    // 全靠它。常见的 night.css 就用 @import 引入 night/ 下的
    // 三个 .dark.css。只服务 <主题名>.css 会让这些引用全部 404，
    // 症状是"主题加载了但字体不对"，极难排查。
    //
    // 注意用的是打开文档那一轮的输出：主题自测在 openPath 里执行，
    // 不带文档的那一轮根本不会跑到。
    const 主题 = /主题协议自测：(.*)$/m.exec(文本)
    断言(主题 !== null, '应输出主题协议自测结果')
    if (主题) {
      const 结果 = 主题[1]
      断言(/主题本体=200/.test(结果), `主题本体应可加载，实际：${结果}`)
      断言(/子目录资源=200/.test(结果), `主题子目录资源应可加载，实际：${结果}`)
      断言(/缺失文件=404/.test(结果), `缺失的主题文件应返回 404 而不是报错，实际：${结果}`)
      断言(/目录穿越=404/.test(结果), `目录穿越必须被挡住，实际：${结果}`)

      // --- 内置主题是否真的装上了 ---------------------------------------
      // "装了没有"会静默出错：文件没写进 themes 目录、`@name` 解析失败、
      // 深色标记判错——三种情况在界面上都只表现为"下拉框里少一项"，
      // 不报任何错。早先内置主题只在**首次启动**写入，于是新增主题时
      // 已有用户永远拿不到——正是靠下面这几条发现的。
      断言(/内置=3/.test(结果), `应当装有 3 款内置主题，实际：${结果}`)
      断言(/parchment=黄皮纸/.test(结果), `应有「黄皮纸」，实际：${结果}`)
      断言(/moon-light=月之亮面/.test(结果), `应有「月之亮面」，实际：${结果}`)
      断言(
        /moon-dark=月之暗面\(暗\)/.test(结果),
        `应有「月之暗面」且标为深色，实际：${结果}`
      )
      断言(/全部可读=true/.test(结果), `每款内置主题都应能读到正文，实际：${结果}`)

      console.log(`  ${'主题协议'.padEnd(28)} ${结果}`)
    }

    // ------------------------------------------------------ 图片渲染 --
  // 图片管线（存储、插入、引用生成）早就通了，但屏幕上一直只显示
  // `![替代](地址)` 的源码——**渲染**这一步整个缺失，而纯函数断言
  // 全都通过。这一层专门盯"图片真的变成了 <img>"。
  //
  // 素材里四种情况各一份：相对路径能加载的、指向不存在文件的、
  // 远程地址的、以及夹在句子中间的。分开数才能区分
  // 「没渲染」与「渲染了但加载失败」——两者的修复方向完全不同。
  {
    const { 文本: 图输出 } = await 运行冒烟('fixtures/图片测试.md')
    const 计数行 = /渲染 DOM 计数：(.*)$/m.exec(图输出)
    断言(计数行 !== null, '应输出图片测试的 DOM 计数')

    if (计数行) {
      const 取数 = (名) => {
        const 匹配 = new RegExp(`${名}=(\\d+)`).exec(计数行[1])
        return 匹配 ? Number(匹配[1]) : -1
      }
      const 图片 = 取数('图片')
      const 失败 = 取数('图片失败')
      const 独占行 = 取数('独占行图片')
      const 解析数 = Number(/Image=(\d+)/.exec(图输出)?.[1] ?? 0)

      断言(解析数 === 4, `图片素材应有 4 个 Image 节点，实际 ${解析数}`)
      // 三张能加载（两张独占一行 + 一张行内），一张渲染成失败占位
      断言(图片 === 3, `应有 3 张图片渲染成 <img>，实际 ${图片}`)
      断言(失败 === 1, `应有 1 张渲染成失败占位，实际 ${失败}`)
      // 独占一行的有三张；行内那张不该带这个类，否则它会被居中成块
      断言(独占行 === 3, `应有 3 行被标为独占行图片，实际 ${独占行}`)

      console.log(
        `  ${'图片渲染'.padEnd(28)} 解析 ${解析数} 个 · 成图 ${图片} 张 · 失败占位 ${失败} 个 · 独占行 ${独占行} 行`
      )
    }

    // -------------------------------------------------------- 数学渲染 --
  // 扫描对了不代表渲染出来了。而且这里是**块级装饰的硬约束**暴露的地方：
  // 跨行替换不能由插件提供（"Decorations that replace line breaks may not be
  // specified via plugins"），加 `block: true` 也还是不行
  // （"Block decorations may not be specified via plugins"）——
  // 块级装饰只能来自 StateField。两条都踩过，所以这里必须真的数一遍 DOM。
  {
    const { 文本: 数学输出 } = await 运行冒烟('fixtures/数学公式.md')
    const 计数行 = /渲染 DOM 计数：(.*)$/m.exec(数学输出)
    断言(计数行 !== null, '应输出数学公式测试的 DOM 计数')

    if (计数行) {
      const 公式数 = Number(/数学公式=(\d+)/.exec(计数行[1])?.[1] ?? 0)
      // 素材里有 2 个行内公式 + 2 个块级公式
      断言(公式数 === 4, `应渲染出 4 个公式，实际 ${公式数}`)

      // 装饰层不能报错。块级装饰的两个限制都是抛异常的形式，
      // 一旦违反，日志里会出现 renderer:error。
      断言(
        !/renderer:error/.test(数学输出),
        '数学渲染不应产生渲染层错误（块级装饰必须是 StateField 提供）'
      )

      console.log(`  ${'数学公式渲染'.padEnd(26)} 渲染 ${公式数} 个 · 无渲染层错误`)
    }
  }

  // -------------------------------------------------------- 图表渲染 --
  // 与数学公式同一套 StateField 模式（插件不能提供块级装饰），
  // 但多一层麻烦：Mermaid 是**异步**渲染的，先出占位再换成 SVG。
  // 所以断言必须等它走到终态，否则计数会时对时错。
  {
    const { 文本: 图表输出 } = await 运行冒烟('fixtures/图表测试.md')
    const 计数行 = /渲染 DOM 计数：(.*)$/m.exec(图表输出)
    断言(计数行 !== null, '应输出图表测试的 DOM 计数')

    if (计数行) {
      const 取数 = (名) => {
        const 匹配 = new RegExp(`${名}=(\\d+)`).exec(计数行[1])
        return 匹配 ? Number(匹配[1]) : 0
      }
      const 图表 = 取数('图表')
      const 出图 = 取数('图表已出图')
      const 失败 = 取数('图表失败')
      const 未完成 = 取数('图表未完成')

      // 素材里三个 mermaid 围栏：流程图、时序图、一个语法错误的
      断言(图表 === 3, `三个 mermaid 围栏都应变成图表组件，实际 ${图表}`)
      断言(出图 === 2, `两个合法图表应渲染出 SVG，实际 ${出图}`)
      // 语法错误要显示错误与源码，而不是白屏或崩溃
      断言(失败 === 1, `语法错误的图表应标记为失败，实际 ${失败}`)
      // 不能有图表卡在渲染中——那说明等待逻辑或渲染流程断了
      断言(未完成 === 0, `不应有图表卡在渲染中，实际 ${未完成}`)
      // 普通代码块不受影响
      断言(取数('代码块行') === 3, '普通 js 代码块不应被当成图表')

      断言(!/renderer:error/.test(图表输出), '图表渲染不应产生渲染层错误')

      console.log(
        `  ${'图表渲染'.padEnd(28)} 组件 ${图表} 个 · 出图 ${出图} 个 · 失败占位 ${失败} 个 · 未完成 ${未完成} 个`
      )
    }
  }

  // ---------------------------------------------------- 代码语言着色 --
  // 围栏代码块的语言识别。
  //
  // 这里抓的是一个**看起来完全正常**的缺陷：语言标签显示了、解析器也跑了，
  // 但代码一个颜色都没有。根因在 CodeMirror 的取值逻辑——
  // `let main = facet(highlighterFacet); return main.length ? main : facet(fallbackHighlighter)`，
  // 也就是"只要有非 fallback 的高亮风格，fallback 就整个不生效"，
  // 于是那份 `syntaxHighlighting(defaultHighlightStyle, { fallback: true })`
  // 一行都没起作用，而自定义风格里又没有编程语言的标签。
  //
  // **必须分语言标签逐个断言**：只数"着色总数"的话，
  // "只有注释上了色、关键字没上"也会显示成通过。
  {
    const { 文本: 代码输出 } = await 运行冒烟('fixtures/代码语言.md')
    const 行 = /渲染 DOM 计数：(.*)$/m.exec(代码输出)
    断言(行 !== null, '应输出代码语言素材的 DOM 计数')

    if (行) {
      const 取数 = (名) => {
        const m = new RegExp(`${名}=(\\d+)`).exec(行[1])
        return m ? Number(m[1]) : 0
      }
      // 三种语言各一段：JavaScript / Python / Rust
      断言(取数('语言标签') === 3, `三段围栏都应有语言标签，实际 ${取数('语言标签')}`)
      断言(取数('代码关键字') >= 5, `关键字应着色，实际 ${取数('代码关键字')}`)
      断言(取数('代码字符串') >= 3, `字符串字面量应着色，实际 ${取数('代码字符串')}`)
      断言(取数('代码注释') >= 3, `注释应着色，实际 ${取数('代码注释')}`)
      断言(取数('代码函数') >= 2, `函数名应着色，实际 ${取数('代码函数')}`)
      断言(取数('代码数字') >= 2, `数字字面量应着色，实际 ${取数('代码数字')}`)
      // 总数兜底：任何一类掉到 0 都会被上面几条之一抓住，
      // 这条用来防"整体没跑"——例如解析器根本没接上
      断言(取数('代码着色总数') >= 30, `代码着色总数应可观，实际 ${取数('代码着色总数')}`)

      断言(!/renderer:error/.test(代码输出), '代码着色不应产生渲染层错误')

      console.log(
        `  ${'代码语言着色'.padEnd(28)} ` +
          `语言标签 ${取数('语言标签')} · 着色 ${取数('代码着色总数')} ` +
          `（关键字 ${取数('代码关键字')} 字符串 ${取数('代码字符串')} 注释 ${取数('代码注释')} 函数 ${取数('代码函数')}）`
      )
    }
  }

  // -------------------------------------------------------- 全屏退出 --
  // 全屏时 Windows 会把标题栏连同最小化/最大化/关闭一起隐藏，
  // **没有任何可点的退出入口**。如果 Esc 不管用，用户就真的卡住了。
  //
  // 这件事在开发时极难发现——开发者知道 F11 能切回来，普通用户不知道。
  // 所以断言必须覆盖"真的按一次 Esc"：自测用 sendInputEvent 走真实输入管线，
  // 因此会经过 before-input-event，与用户按键完全同一条路。
  {
    const 行 = /全屏自测：(.*)$/m.exec(文本)
    断言(行 !== null, '应输出全屏自测结果')

    if (行) {
      const 结果 = 行[1]
      断言(/进入全屏=true/.test(结果), `应当能进入全屏，实际：${结果}`)
      // 这一条就是全部：全屏后按 Esc 必须退出，否则用户没有出口
      断言(
        /按Esc后仍全屏=false/.test(结果),
        `全屏后按 Esc 应当退出全屏，实际：${结果}`
      )
      console.log(`  ${'全屏与退出'.padEnd(28)} ${结果}`)
    }
  }

  // ---------------------------------------------------- 复制为图片 --
  // 这条链路几乎每一环都可能静默失败：离屏窗口没画出来、图片没解码完就截、
  // 内容高度没量对导致只截了头部——三种情况的结果都是"拿到一张图"，
  // 看起来完全正常。所以断言必须落在**尺寸**上。
  {
    const 行 = /复制为图片自测：(.*)$/m.exec(文本)
    断言(行 !== null, '应输出复制为图片自测结果')

    if (行) {
      const 结果 = 行[1]
      断言(/短=900×\d+/.test(结果), `短文档应截出 900 宽的图，实际：${结果}`)
      断言(/长=900×\d+/.test(结果), `长文档应截出 900 宽的图，实际：${结果}`)
      // 这一条抓的是"高度没量对、只截了窗口可视区"——
      // 那种情况下长短文档会得到**一样高**的图。
      断言(/长图更高=是/.test(结果), `长文档的图应当更高，实际：${结果}`)
      断言(/未截断=true/.test(结果), `测试文档不应触发截断，实际：${结果}`)
      断言(!/失败:/.test(结果), `截图不应失败，实际：${结果}`)

      console.log(`  ${'复制为图片'.padEnd(28)} ${结果}`)
    }
  }

  // ------------------------------------------------------ 多文档标签 --
  // 盯住整个多文档实现里唯一一处"顺序写错就静默丢数据"的地方：
  // 替换视图状态之前有没有把当前标签的编辑器状态写回。
  //
  // 这个用例真的抓到了缺陷：`file.new` 与 `openPath` 都是先
  // `view.setState()` 再 `加入()`，于是"新建文件"会把当前文档里
  // 未保存的改动直接丢掉，而且没有任何提示。
  {
    // 自测结果由 `fixtures/块级最小.md` 那次冒烟带回（`文本`）。
    const 标签行 = /多文档标签自测：(.*)$/m.exec(文本)
    断言(标签行 !== null, '应输出多文档标签自测结果')

    if (标签行) {
      const 结果 = 标签行[1]
      // 这一条就是全部：在甲里改、切到乙、切回甲，改动必须在
      断言(/甲标记在=true\/切回后=true/.test(结果), `切回原文档后改动应保留，实际：${结果}`)
      断言(/长度一致=true/.test(结果), `切回后内容长度应一致，实际：${结果}`)
      // 乙的内容也不该被甲的覆盖
      断言(/乙内容未串=true/.test(结果), `两个文档的内容不应互相串，实际：${结果}`)
      // CodeMirror 的历史住在 EditorState 里，切文档后应当各管各的
      断言(/撤销只影响乙=true/.test(结果), `撤销不应跨文档生效，实际：${结果}`)
      // 关掉的文档要能找回来（未保存的改动只有那份备份）
      断言(/可重开=true/.test(结果), `关闭后的文档应能重新打开，实际：${结果}`)
      // 同一个文件开两份会互相覆盖，是最讨厌的坑之一
      断言(/同文件去重=是/.test(结果), `同一个文件不应打开两份，实际：${结果}`)
      断言(!/renderer:error/.test(文本), '标签操作不应产生渲染层错误')

      console.log(`  ${'多文档标签'.padEnd(28)} ${结果}`)
    }
  }

  // ------------------------------------------------------ 图片右键菜单 --
    // 菜单是"点了没反应也看不出来"的典型：回调没注册、位置反查失败、
    // 菜单被立刻关掉——三种情况都只是"右键没反应"，没有任何报错。
    // 所以真的在渲染出来的图片上触发一次 contextmenu，再数菜单项。
    //
    // 用**单独的素材**：这里需要一张远程图来验证"远程图上部分菜单项置灰"，
    // 而上面那个渲染计数用例断言的是精确数字，不能有外部依赖。
    // 两者共用一份素材时，渲染计数会被网络状况影响。
    const { 文本: 菜单输出 } = await 运行冒烟('fixtures/图片菜单.md')
    const 菜单 = /图片右键菜单自测：本地=(\d+)\/(\d+)\/(\d+) 远程=(\d+)\/(\d+)\/(\d+) 关闭后残留=(\d+)/.exec(
      菜单输出
    )
    断言(菜单 !== null, '应输出图片右键菜单自测结果')
    if (菜单) {
      const 本地项 = Number(菜单[1])
      const 本地禁用 = Number(菜单[2])
      const 远程项 = Number(菜单[4])
      const 远程禁用 = Number(菜单[5])
      const 残留 = Number(菜单[7])

      断言(本地项 >= 8, `本地图片的菜单应有足够项，实际 ${本地项}`)
      // 本地图片时上传、重命名、复制、删除都该可用
      断言(本地禁用 === 0, `本地图片不应有置灰项，实际 ${本地禁用}`)
      断言(
        远程项 === 本地项,
        `两种图片的菜单项数应一致（只是可点状态不同），实际 ${本地项} vs ${远程项}`
      )
      // 远程图片时那 5 项需要本地文件的操作必须置灰——
      // 点下去只会弹一句"没有本地文件"，不如直接不让点
      断言(远程禁用 >= 4, `远程图片应有若干置灰项，实际 ${远程禁用}`)
      断言(残留 === 0, `关闭菜单后 DOM 不应有残留，实际 ${残留}`)

      console.log(
        `  ${'图片右键菜单'.padEnd(26)} 本地 ${本地项} 项全可用 · 远程 ${远程禁用} 项置灰 · 关闭无残留`
      )
    }
  }

  // -------------------------------------------------------- 侧边栏渲染 --
    // 大纲提取有纯函数断言兜着，但"提取对了"不等于"渲染出来了"。
    // 这里真的把侧边栏显示出来、真的数一遍 DOM 里的条目，把两步之间的缝补上。
    const 侧边 = /侧边栏渲染自测：(.*)$/m.exec(文本)
    断言(侧边 !== null, '应输出侧边栏渲染自测结果')
    if (侧边) {
      const 结果 = 侧边[1]
      const 标题数 = Number(/标题数=(\d+)/.exec(结果)?.[1] ?? -1)
      const 大纲项 = Number(/大纲项=(\d+)/.exec(结果)?.[1] ?? -1)
      断言(标题数 > 0, `样本应至少有一个标题，实际：${结果}`)
      断言(
        大纲项 === 标题数,
        `渲染出的大纲条目数应与标题数一致，实际：${结果}`
      )
      断言(/文件树根=已定位/.test(结果), `文件树应能定位到所在目录，实际：${结果}`)
      const 文件项 = Number(/文件项=(\d+)/.exec(结果)?.[1] ?? 0)
      断言(文件项 > 0, `文件树应列出条目，实际：${结果}`)
      console.log(`  ${'侧边栏渲染'.padEnd(28)} ${结果}`)
    }

    // -------------------------------------------------------- 编辑模式 --
    // 专注模式/打字机模式是「设置 → body 类 → CSS/滚动」的链路，
    // 中间任何一环断了都不会报错，只是看起来没反应。所以真的切一次、
    // 真的数一遍带 md-focus 的行。
    const 模式 = /编辑模式自测：(.*)$/m.exec(文本)
    断言(模式 !== null, '应输出编辑模式自测结果')
    if (模式) {
      const 结果 = 模式[1]
      const 专注行 = Number(/专注行=(\d+)/.exec(结果)?.[1] ?? 0)
      断言(专注行 > 0, `专注模式应给当前块加上 md-focus，实际：${结果}`)
      断言(/专注类=true/.test(结果), `应设置 body.on-focus-mode，实际：${结果}`)
      断言(/打字机类=true/.test(结果), `应设置 body.selfmd-typewriter-mode，实际：${结果}`)
      // 两个模式互不干扰：开专注模式时不该顺带挂上打字机类
      断言(/专注时无打字机类=true/.test(结果), `专注模式不应连带开启打字机模式，实际：${结果}`)
      // 拼写检查走的是"设置 → 内容元素的属性"，与前两个走 body 类的链路不同。
      // 断了不会报错，只是红波浪线不出现——而用户多半会以为"这个词本来就拼对了"。
      断言(/拼写开启=true/.test(结果), `开启拼写检查时内容元素应带 spellcheck=true，实际：${结果}`)
      断言(/拼写关闭=false/.test(结果), `关闭拼写检查时内容元素应带 spellcheck=false，实际：${结果}`)
      console.log(`  ${'编辑模式'.padEnd(30)} ${结果}`)
    }

    // ---------------------------------------------------- 偏好设置界面 --
    // 表自测只能证明"描述对了"；这里真的把面板打开、真的数一遍渲染出的行，
    // 再切一次搜索与关闭，把"描述 → 界面"这一段补上。
    const 偏好界面 = /偏好设置界面自测：(.*)$/m.exec(文本)
    断言(偏好界面 !== null, '应输出偏好设置界面自测结果')
    if (偏好界面) {
      const 结果 = 偏好界面[1]
      const 分区 = Number(/分区=(\d+)/.exec(结果)?.[1] ?? 0)
      const 首屏行 = Number(/首屏行=(\d+)/.exec(结果)?.[1] ?? 0)
      const 搜索命中 = Number(/搜索命中=(\d+)/.exec(结果)?.[1] ?? -1)
      const 清空后行 = Number(/清空后行=(\d+)/.exec(结果)?.[1] ?? -1)
      断言(分区 >= 5, `偏好设置应有至少 5 个分区，实际：${结果}`)
      断言(首屏行 > 0, `首个分区应渲染出设置项，实际：${结果}`)
      断言(搜索命中 > 0, `搜索「字体」应有命中，实际：${结果}`)
      // 清空搜索后必须回到分类视图，且行数与搜索前一致——
      // 不一致说明重绘时有状态残留
      断言(
        清空后行 === 首屏行,
        `清空搜索后应回到原行数 ${首屏行}，实际 ${清空后行}`
      )
      断言(/关闭后残留=0/.test(结果), `关闭面板后 DOM 不应有残留，实际：${结果}`)
      console.log(`  ${'偏好设置界面'.padEnd(26)} ${结果}`)
    }

    // ---------------------------------------------------- 草稿与崩溃恢复 --
    // 重点是一条**竞态守卫**：保存是异步的，期间用户可能又敲了几个字。
    // 若保存成功后无条件删草稿，那部分新内容就永远丢了。
    const { 文本: 草稿输出 } = await 运行冒烟(null, ['--smoke-drafts'])
    const 草稿 = /草稿与恢复：(\d+)\/(\d+) 项通过/.exec(草稿输出)
    断言(草稿 !== null, '应输出草稿与恢复结果')
    if (草稿) {
      断言(草稿[1] === 草稿[2], `草稿与恢复应全部通过，实际 ${草稿[1]}/${草稿[2]}`)
      console.log(`  ${'草稿与崩溃恢复'.padEnd(26)} ${草稿[1]}/${草稿[2]} 项通过`)
    }
    const 草稿失败 = /草稿与恢复：未通过 — (.+)$/m.exec(草稿输出)
    断言(草稿失败 === null, `草稿与恢复未通过项：${草稿失败?.[1] ?? ''}`)

    // -------------------------------------------------------- 导出端到端 --
    // 纯函数断言只能证明"渲染器算得对"；这一层真的导出一次、把文件读回来，
    // 才能证明整条链路（渲染 → 拼模板 → 内联样式 → 落盘）是通的。
    const { 文本: 导出输出 } = await 运行冒烟(null, ['--smoke-export'])
    const 导出 = /导出端到端：(\d+)\/(\d+) 项通过\s+文件 (\d+) 字符/.exec(导出输出)
    断言(导出 !== null, '应输出导出端到端结果')
    if (导出) {
      const 通过 = Number(导出[1])
      const 总数 = Number(导出[2])
      断言(通过 === 总数, `导出端到端应全部通过，实际 ${通过}/${总数}`)
      断言(Number(导出[3]) > 2000, `导出文件不应为空，实际 ${导出[3]} 字符`)
      console.log(`  ${'导出端到端'.padEnd(28)} ${通过}/${总数} 项通过，文件 ${导出[3]} 字符`)
    }
    // 导出失败时主进程会打印未通过项的名字，这里直接把它们捞出来报错
    const 导出失败 = /导出端到端：未通过 — (.+)$/m.exec(导出输出)
    断言(导出失败 === null, `导出端到端未通过项：${导出失败?.[1] ?? ''}`)
  }

  // ------------------------------------------------------ 图片端到端 --
  // 纯函数断言只能证明"决策算得对"；这里让应用真的复制一个文件、真的往文档里
  // 写一行引用。两条真实缺陷就是被这一步抓出来的：引用写到了 YAML 前置元数据
  // **之前**（导致整块元数据失效），以及中文路径被整段百分号编码。
  {
    const { 文本: 图输出 } = await 运行冒烟(null, ['--smoke-image'])
    const 匹配 = /图片插入端到端：(.*)$/m.exec(图输出)
    断言(匹配 !== null, '应输出图片插入端到端结果')

    if (匹配) {
      const 结果 = 匹配[1]
      断言(结果.includes('成功=1'), `图片应插入成功，实际：${结果}`)
      断言(结果.includes('文件已落盘=true'), `图片文件应真的写入目标目录，实际：${结果}`)

      const 文档 = /文档=(.*)$/.exec(结果)?.[1] ?? ''
      断言(
        文档.startsWith('---⏎image-folder: 图⏎---⏎'),
        `前置元数据应仍位于文档开头，实际：${文档}`
      )
      断言(
        文档.includes('![样本](图/样本.png)'),
        `引用应为可读的中文相对路径，实际：${文档}`
      )
      断言(
        文档.indexOf('![样本]') > 文档.lastIndexOf('---⏎'),
        `图片应插入在前置元数据之后，实际：${文档}`
      )

      console.log(`  ${'图片插入端到端'.padEnd(24)} 落盘与引用均已验证`)
    }
  }

  // ---------------------------------------------------------------- 汇总 --
  console.log('')
  if (失败列表.length === 0) {
    console.log(`✅ 全部通过：${通过数} 项断言`)
    rmSync(临时目录, { recursive: true, force: true })
    process.exit(0)
  }
  console.log(`❌ ${失败列表.length} 项失败（通过 ${通过数} 项）：`)
  for (const 描述 of 失败列表) console.log(`   · ${描述}`)
  rmSync(临时目录, { recursive: true, force: true })
  process.exit(1)
}

